/* assets/js/main.js
 * -------------------------------------------------
 * Core UI logic for the BountyWatch dashboard
 * – navigation hamburger toggle
 * – fetch & cache JSON scope‑change data
 * – render “ScopeCard” components
 *
 * Dependencies (loaded via CDN):
 *   • axios   – window.axios
 *   • date-fns – window.dateFns
 *
 * This file is an ES‑module (type="module" on the <script> tag)
 * ------------------------------------------------- */

(() => {
  /* -----------------------------------------------------------------------
   * Configuration
   * --------------------------------------------------------------------- */
  const CONFIG = {
    // Relative URL of the JSON payload generated by the CI pipeline
    API_ENDPOINT: '/data/scope.json',

    // Selectors – keep them in sync with the HTML markup
    SELECTORS: {
      NAV_TOGGLE: '#nav-toggle',          // hamburger button
      NAV_MENU: '#nav-menu',              // collapsible <nav>
      CARD_CONTAINER: '#scope-cards',     // <section> where cards are injected
      LOADER: '#loader',                  // optional loading spinner
      ERROR: '#error'                     // optional error placeholder
    },

    // CSS classes used for UI states
    CLASSES: {
      OPEN: 'is-open',
      LOADING: 'is-loading',
      ERROR: 'is-error'
    }
  };

  /* -----------------------------------------------------------------------
   * Utility helpers
   * --------------------------------------------------------------------- */
  const $ = (sel) => document.querySelector(sel);
  const $$ = (sel) => Array.from(document.querySelectorAll(sel));

  // Simple debounce – useful if you ever add resize listeners
  const debounce = (fn, wait) => {
    let timeout;
    return (...args) => {
      clearTimeout(timeout);
      timeout = setTimeout(() => fn.apply(this, args), wait);
    };
  };

  // Safe JSON parsing with fallback
  const safeParse = (text) => {
    try {
      return JSON.parse(text);
    } catch (e) {
      console.error('Failed to parse JSON', e);
      return null;
    }
  };

  // Human‑readable date (e.g. “Oct 15, 2026”)
  const formatDate = (isoString) => {
    if (!window.dateFns) return isoString;
    try {
      const date = new Date(isoString);
      return window.dateFns.format(date, 'PPP');
    } catch {
      return isoString;
    }
  };

  /* -----------------------------------------------------------------------
   * Navigation – hamburger toggle (mobile‑first)
   * --------------------------------------------------------------------- */
  const initNavigation = () => {
    const toggleBtn = $(CONFIG.SELECTORS.NAV_TOGGLE);
    const navMenu = $(CONFIG.SELECTORS.NAV_MENU);

    if (!toggleBtn || !navMenu) return;

    // Ensure ARIA attributes are present for accessibility
    toggleBtn.setAttribute('aria-controls', navMenu.id);
    toggleBtn.setAttribute('aria-expanded', 'false');

    const toggleMenu = () => {
      const isOpen = navMenu.classList.toggle(CONFIG.CLASSES.OPEN);
      toggleBtn.setAttribute('aria-expanded', isOpen);
    };

    toggleBtn.addEventListener('click', toggleMenu);
    // Close menu on resize when it becomes a desktop layout
    window.addEventListener(
      'resize',
      debounce(() => {
        if (window.innerWidth >= 768 && navMenu.classList.contains(CONFIG.CLASSES.OPEN)) {
          navMenu.classList.remove(CONFIG.CLASSES.OPEN);
          toggleBtn.setAttribute('aria-expanded', 'false');
        }
      }, 200)
    );
  };

  /* -----------------------------------------------------------------------
   * Data fetching & caching
   * --------------------------------------------------------------------- */
  const fetchScopeData = async () => {
    const loader = $(CONFIG.SELECTORS.LOADER);
    const errorBox = $(CONFIG.SELECTORS.ERROR);
    if (loader) loader.classList.add(CONFIG.CLASSES.LOADING);

    try {
      const response = await window.axios.get(CONFIG.API_ENDPOINT, {
        headers: { Accept: 'application/json' },
        timeout: 15000
      });
      const data = safeParse(JSON.stringify(response.data));
      if (!data) throw new Error('Invalid JSON payload');
      return data;
    } catch (err) {
      console.error('Scope data fetch failed:', err);
      if (errorBox) {
        errorBox.textContent = 'Unable to load scope changes – please try again later.';
        errorBox.classList.add(CONFIG.CLASSES.ERROR);
      }
      return null;
    } finally {
      if (loader) loader.classList.remove(CONFIG.CLASSES.LOADING);
    }
  };

  /* -----------------------------------------------------------------------
   * ScopeCard component – pure DOM creation (no framework)
   * --------------------------------------------------------------------- */
  const createScopeCard = (program) => {
    // Expected program shape:
    // {
    //   name: string,
    //   id: string,
    //   platform: 'bugcrowd' | 'hackerone' | ...,
    //   url: string,
    //   added: string[],   // new scope entries
    //   removed: string[], // removed scope entries
    //   date: ISOString
    // }

    const card = document.createElement('article');
    card.className = 'scope-card';
    card.dataset.programId = program.id;

    // Header – program name + platform badge
    const header = document.createElement('header');
    header.className = 'scope-card__header';

    const title = document.createElement('h3');
    title.className = 'scope-card__title';
    const link = document.createElement('a');
    link.href = program.url;
    link.target = '_blank';
    link.rel = 'noopener noreferrer';
    link.textContent = program.name;
    title.appendChild(link);
    header.appendChild(title);

    const badge = document.createElement('span');
    badge.className = 'badge badge--secondary';
    badge.textContent = program.platform;
    header.appendChild(badge);
    card.appendChild(header);

    // Meta – date of change
    const meta = document.createElement('time');
    meta.className = 'scope-card__date';
    meta.dateTime = program.date;
    meta.textContent = formatDate(program.date);
    card.appendChild(meta);

    // Body – added / removed lists
    const body = document.createElement('div');
    body.className = 'scope-card__body';

    const listFactory = (items, type) => {
      if (!items || items.length === 0) return null;
      const wrapper = document.createElement('section');
      wrapper.className = `scope-card__list scope-card__list--${type}`;

      const heading = document.createElement('h4');
      heading.textContent = type === 'added' ? 'Added' : 'Removed';
      wrapper.appendChild(heading);

      const ul = document.createElement('ul');
      items.forEach((item) => {
        const li = document.createElement('li');
        li.textContent = item;
        ul.appendChild(li);
      });
      wrapper.appendChild(ul);
      return wrapper;
    };

    const addedList = listFactory(program.added, 'added');
    const removedList = listFactory(program.removed, 'removed');

    if (addedList) body.appendChild(addedList);
    if (removedList) body.appendChild(removedList);
    if (!addedList && !removedList) {
      const empty = document.createElement('p');
      empty.className = 'scope-card__empty';
      empty.textContent = 'No scope changes recorded for this entry.';
      body.appendChild(empty);
    }

    card.appendChild(body);
    return card;
  };

  /* -----------------------------------------------------------------------
   * Rendering pipeline
   * --------------------------------------------------------------------- */
  const renderScopeCards = (programs) => {
    const container = $(CONFIG.SELECTORS.CARD_CONTAINER);
    if (!container) return;

    // Clear any previous content
    container.innerHTML = '';

    // Sort by most recent change first
    const sorted = [...programs].sort(
      (a, b) => new Date(b.date) - new Date(a.date)
    );

    sorted.forEach((program) => {
      const cardEl = createScopeCard(program);
      container.appendChild(cardEl);
    });
  };

  /* -----------------------------------------------------------------------
   * Init – orchestrates everything once DOM is ready
   * --------------------------------------------------------------------- */
  const init = async () => {
    initNavigation();

    const data = await fetchScopeData();
    if (!data) return; // error UI already displayed by fetchScopeData

    // The JSON payload may be an object with a `programs` array or a raw array.
    const programs = Array.isArray(data) ? data : data.programs || [];
    if (programs.length === 0) {
      const container = $(CONFIG.SELECTORS.CARD_CONTAINER);
      if (container) container.textContent = 'No scope changes for the selected period.';
      return;
    }

    renderScopeCards(programs);
  };

  // Run after the document is fully parsed
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();